import {test,expect,activeSession} from './session-fixture.js';
for(const width of [1280,360]) test(`blocos proporcionais, filtros e percurso ${width}`,async({browser})=>{
 const context=await browser.newContext({viewport:{width,height:900},hasTouch:width===360,isMobile:width===360});
 await activeSession(context);const page=await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/#/leads');
 await page.getByRole('button',{name:'Adicionar comparação Aurora e Horizonte'}).click();
 const blocks=page.getByRole('region',{name:'Blocos de valor'});
 const aurora=blocks.locator('[data-item="l0"]'),horizonte=blocks.locator('[data-item="l1"]');
 await expect(aurora).toContainText('200.000,00');await expect(horizonte).toContainText('10.000,00');
 const area=async el=>el.locator('.scale-area').evaluate(el=>el.getBoundingClientRect().width*el.getBoundingClientRect().height);
 expect(await area(aurora)/await area(horizonte)).toBeCloseTo(20,1);
 expect((await aurora.boundingBox()).height).toBeGreaterThan((await horizonte.boundingBox()).height);
 expect((await horizonte.boundingBox()).height).toBeGreaterThanOrEqual(68);
 await page.screenshot({path:`evidencias/valores-leads-${width}.png`,fullPage:true});
 if(width===360) await horizonte.tap();else {await horizonte.focus();await page.keyboard.press('Enter');}
 const dialog=page.getByRole('dialog',{name:'Loja Horizonte'});await expect(dialog).toBeVisible();
 await expect(dialog).toContainText('Clara Luz');await expect(dialog).toContainText('Squad Horizonte');
 await page.keyboard.press('Escape');await expect(dialog).not.toBeVisible();await expect(horizonte).toBeFocused();
 await page.getByLabel('Agrupar blocos').selectOption('stage');
 await page.getByRole('combobox',{name:'Segmento da contratante',exact:true}).selectOption('Finanças & Pagamentos');
 await page.getByLabel('Fase / Tipo').selectOption('Delivery');
 await page.getByRole('combobox',{name:'Subárea CITi',exact:true}).selectOption('a0');
 await page.getByRole('combobox',{name:'Estágio',exact:true}).selectOption('Ganho');
 await expect(blocks.locator('.value-block')).toHaveCount(1);
 await page.reload();await expect(blocks.locator('.value-block')).toHaveCount(1);
 await aurora.click();await page.getByRole('dialog').getByRole('link',{name:'Abrir projeto vinculado →'}).click();
 await expect(page).toHaveURL(/segmento=/);await expect(page.getByLabel('Status do projeto')).toBeVisible();
 await page.getByRole('link',{name:'Explorar squad →'}).click();
 await expect(page.getByRole('heading',{name:'Squad Aurora IA',exact:true})).toBeVisible();
 await expect(page.getByText('Ana Lima',{exact:true}).first()).toBeVisible();
 await page.goto('/#/projetos');
 await page.getByRole('button',{name:'Adicionar comparação Aurora e Horizonte'}).click();
 await expect(blocks.locator('.value-block')).toHaveCount(2);
 await page.screenshot({path:`evidencias/valores-projetos-${width}.png`,fullPage:true});
 const pAurora=blocks.getByRole('button',{name:/Portal Aurora/}),pHorizonte=blocks.getByRole('button',{name:/Loja Horizonte/});
 expect(await area(pAurora)/await area(pHorizonte)).toBeCloseTo(20,1);
 await pAurora.click();await expect(page.getByRole('dialog')).toContainText('Delivery');await page.getByRole('button',{name:'Fechar detalhe'}).click();
 await page.getByLabel('Agrupar blocos').selectOption('squad');
 await page.getByRole('combobox',{name:'Segmento da contratante',exact:true}).selectOption('Varejo & E-commerce');
 await page.getByLabel('Fase / Tipo').selectOption('Discovery');await page.getByRole('combobox',{name:'Área',exact:true}).selectOption('a2');
 await expect(blocks.locator('.value-block')).toHaveCount(1);await expect(pHorizonte).toBeVisible();
 await page.getByLabel('Buscar projetos').fill('ausente');await expect(blocks.locator('.value-block')).toHaveCount(0);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 expect(errors).toEqual([]);await context.close();
});
