import {test,expect,activeSession} from './session-fixture.js';
import {seed} from '../src/domain.js';
import {addValueDemo} from '../src/services/leadProjectService.js';

for (const width of [1280,360]) test('mosaico, carteira e projeto ('+width+'px)', async ({browser}) => {
  const context=await browser.newContext({viewport:{width,height:900},hasTouch:width===360,isMobile:width===360});
  await activeSession(context);
  await context.addInitScript(state=>localStorage.setItem('central-citi-v1',JSON.stringify(state)),addValueDemo(structuredClone(seed)));
  const page=await context.newPage();
  await page.goto('/#/projetos');
  await expect(page.getByRole('region',{name:'Blocos de valor'})).toHaveCount(0);
  const mosaic=page.getByRole('group',{name:'Mosaico de projetos pelo valor contratado'});
  await expect(mosaic.locator('.bento-tile')).toHaveCount(2);
  await expect(page.getByText('Ver como tabela',{exact:true})).toHaveCount(0);
  await expect(page.locator('.bento-categories .chart-list')).toHaveCount(0);
  const small = mosaic.getByRole('link',{name:/Loja Horizonte/});
  await expect(small.getByText('Loja Horizonte',{exact:true})).toBeVisible();
  await expect(small.locator('.bento-tile-value')).toHaveText(/R\$\s*10\.000,00/);
  await expect(small.getByText('4,8%',{exact:true})).toBeVisible();
  await small.scrollIntoViewIfNeeded();
  const tileBounds = await small.boundingBox();
  const priceBounds = await small.locator('.bento-tile-value').boundingBox();
  expect(priceBounds.x + priceBounds.width).toBeLessThan(tileBounds.x + tileBounds.width);
  expect(priceBounds.y + priceBounds.height).toBeLessThan(tileBounds.y + tileBounds.height);
  await mosaic.getByRole('link',{name:/Portal Aurora/}).click();
  await expect(page.getByLabel('Status do projeto')).toBeVisible();
  await expect(page.getByRole('region',{name:'Contrato',exact:true})).toHaveCount(0);
  await expect(page.getByRole('region',{name:'Dados do projeto'})).toContainText('200.000,00');
  await expect(page.getByRole('link',{name:/Explorar squad/})).toHaveCount(0);
  await page.goto('/#/projetos');
  await page.getByRole('link',{name:'Todos os projetos →'}).click();
  await page.getByLabel('Segmento da contratante').selectOption('Varejo & E-commerce');
  const portfolio=page.getByRole('region',{name:'Carteira de projetos'});
  await expect(portfolio.locator('.card')).toHaveCount(1);
  await expect(portfolio).toContainText('Loja Horizonte');
  await expect(portfolio).not.toContainText(/squad|integrante|Clara Luz/i);
  const view = page.getByRole('group',{name:'Visualização dos projetos'});
  await view.getByRole('button',{name:'Tabela'}).click();
  const table = portfolio.getByRole('table',{name:'Projetos e contratos'});
  await expect(table.getByRole('row')).toHaveCount(2);
  await expect(table.getByRole('link',{name:'Loja Horizonte'})).toBeVisible();
  await expect(table.getByRole('cell',{name:/R\$\s*10\.000,00/})).toBeVisible();
  await page.reload();
  await expect(view.getByRole('button',{name:'Tabela'})).toHaveAttribute('aria-pressed','true');
  await expect(table.getByRole('row')).toHaveCount(2);
  await view.getByRole('button',{name:'Cartões'}).click();
  await expect(portfolio.locator('.card')).toHaveCount(1);
  await page.getByRole('searchbox',{name:'Buscar projetos'}).fill('ausente');
  await expect(portfolio).toContainText('Nenhum projeto encontrado.');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await context.close();
});
