import {test, expect} from './session-fixture.js';

for (const width of [1280, 390]) test(`prospectos preservam recorte e registro (${width}px)`, async ({page}, testInfo) => {
  await page.setViewportSize({width,height:900});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('/#/leads');
  const funnel = page.getByRole('region',{name:'Funil de leads'});
  const dashboardButton = page.getByRole('group',{name:'Ações de leads'}).getByRole('link',{name:'Novo lead →'});
  const glassStyle = button => button.evaluate(node => {
    const style = getComputedStyle(node);
    return [style.backgroundColor,style.borderRadius,style.minHeight,style.backdropFilter];
  });
  const dashboardButtonStyle = await glassStyle(dashboardButton);
  const switchHeight = (await page.getByRole('group',{name:'Comparar sazonalidade por'}).boundingBox()).height;
  await expect(funnel.locator('.funnel-records')).toHaveCount(0);
  await funnel.getByRole('link',{name:/^Proposta:/}).click();
  await expect(page).toHaveURL(/\/leads\/prospectos\?estagio=Proposta/);
  await expect(page.getByRole('heading',{name:'Todos os leads',exact:true})).toBeVisible();
  const breadcrumb = page.getByRole('navigation',{name:'Caminho da página'});
  await expect(breadcrumb.getByRole('link',{name:'Leads',exact:true})).toHaveAttribute('href','#/leads');
  await expect(breadcrumb.getByText('Todos os leads')).toHaveAttribute('aria-current','page');
  const filterPanel = page.locator('.prospect-filter-module .glass-filters');
  await expect(filterPanel.getByRole('searchbox',{name:'Buscar prospectos'})).toBeVisible();
  const choose = async (scope, label, choice) => {
    await scope.getByRole('button',{name:label,exact:true}).click();
    await scope.getByRole('group',{name:label,exact:true}).getByRole('button',{name:choice}).click();
  };
  const sectorFilter = filterPanel.getByRole('button',{name:'Setor da empresa',exact:true});
  await filterPanel.getByRole('button',{name:'Segmento da contratante',exact:true}).click();
  const segmentOptions = filterPanel.getByRole('group',{name:'Segmento da contratante',exact:true});
  await expect(segmentOptions.getByRole('button')).toHaveText(['Todos','Inovação','Negócios','Tech','Produto','Gente e Gestão']);
  await page.keyboard.press('Escape');
  await expect(segmentOptions).toHaveCount(0);
  await sectorFilter.click();
  const sectorOptions = filterPanel.getByRole('group',{name:'Setor da empresa',exact:true});
  await expect(sectorOptions.getByRole('button',{name:/Agricultura & Agronegócio/})).toContainText('0 leads');
  await expect(sectorOptions).toHaveCSS('overflow-y','auto');
  await page.screenshot({path:testInfo.outputPath('filtro-setores.png')});
  await sectorOptions.getByRole('button',{name:/Não classificado/}).click();
  await expect(page.getByText('Buscar prospectos',{exact:true})).toHaveCount(0);
  const newLead = filterPanel.getByRole('link',{name:'Novo lead →'});
  expect(await glassStyle(newLead)).toEqual(dashboardButtonStyle);
  expect((await filterPanel.locator('.lead-search-field').boundingBox()).height).toBe((await newLead.boundingBox()).height);
  const switcher = page.getByRole('group',{name:'Visualização da carteira'});
  expect((await switcher.boundingBox()).height).toBeCloseTo(switchHeight,0);
  await expect(page.getByText('Carteira de prospectos',{exact:true})).toHaveCount(0);
  await expect(page.getByRole('link',{name:/Voltar ao funil/})).toHaveCount(0);
  await expect(page.getByRole('region',{name:'Todos os leads'})).toHaveCSS('backdrop-filter','none');
  const list = page.getByRole('table',{name:'Lista de oportunidades'});
  await expect(list).toBeVisible();
  await expect(list.getByRole('columnheader')).toHaveText(['Estágio','Empresa','Setor','Valor proposto/contratado','Responsável']);
  const row=list.getByRole('row').filter({has:page.getByRole('link',{name:/App Raiz/})});
  if (width === 390) {
    const scrollArea=page.getByRole('region',{name:'Tabela de prospectos'});
    await scrollArea.focus();
    await page.keyboard.press('ArrowRight');
    await expect.poll(()=>scrollArea.evaluate(node=>node.scrollLeft)).toBeGreaterThan(0);
  }
  await expect(row.locator('.prospect-deal-name strong')).toHaveText('Empresa exemplo 3');
  await expect(row.locator('.prospect-deal-stage')).toHaveText('Proposta');
  const company = row.locator('.prospect-company');
  await expect(company).toContainText('Proposta pendente');
  await expect(company.locator('.lead-pending-label svg')).toBeVisible();
  await expect(row.getByRole('cell').first()).toHaveText('Proposta');
  await expect(row.locator('.prospect-deal-stage i')).toHaveCount(0);
  await expect(row.locator('.prospect-deal-stage')).toHaveCSS('background-image','none');
  await expect(row).not.toContainText('42.000,00');
  await expect(list).toContainText('Sem responsável atribuído');
  await expect(list).not.toContainText('Criação');
  const stage = page.getByRole('group',{name:'Filtrar por estágio'});
  await expect(stage.getByRole('button',{name:/^Proposta/})).toHaveAttribute('aria-pressed','true');
  await expect(stage.locator('.prospect-step-halo')).toHaveCount(1);
  const selectedDot=stage.getByRole('button',{name:/^Proposta/}).locator('.prospect-step-node');
  const dotColor=await selectedDot.evaluate(dot=>getComputedStyle(dot).backgroundColor);
  await expect(row.locator('.prospect-deal-stage')).toHaveCSS('background-image','none');
  await expect(selectedDot).toBeHidden();
  await page.getByRole('searchbox',{name:'Buscar prospectos'}).fill('contato3');
  await list.getByRole('link',{name:/App Raiz/}).click();
  await expect(page).toHaveURL(/\/leads\/l2\?/);
  await expect(page.getByRole('heading',{name:'Empresa exemplo 3',level:1})).toBeVisible();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.locator('.lead-values')).toHaveCount(0);
  await expect(page.getByRole('region',{name:'Dados do lead'})).toContainText('contato3@example.com');
  await expect(page.getByRole('region',{name:'Proposta',exact:true})).toBeVisible();
  const proposalBox = await page.getByRole('region',{name:'Proposta',exact:true}).boundingBox();
  const detailsBox = await page.getByRole('region',{name:'Detalhes do lead',exact:true}).boundingBox();
  expect(detailsBox.y).toBeGreaterThanOrEqual(proposalBox.y + proposalBox.height);
  await page.screenshot({path:testInfo.outputPath('proposta.png')});
  await expect(page.getByRole('heading',{name:'Editar lead'})).toBeVisible();
  await page.getByLabel('Nome da oportunidade').fill('App Raiz revisado');
  await choose(page.getByRole('region',{name:'Editar lead'}), 'Segmento da contratante', 'Tech');
  await page.getByRole('button',{name:'Salvar lead'}).click();
  await breadcrumb.getByRole('link',{name:'Todos os leads',exact:true}).click();
  await expect(page.getByRole('searchbox',{name:'Buscar prospectos'})).toHaveValue('contato3');
  await expect(sectorFilter).toHaveText('Não classificado');
  await choose(filterPanel, 'Segmento da contratante', 'Tech');
  await expect(list.getByRole('link',{name:/App Raiz revisado/})).toBeVisible();
  await choose(filterPanel, 'Segmento da contratante', 'Todos');
  await choose(filterPanel, 'Setor da empresa', 'Todos');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('searchbox',{name:'Buscar prospectos'}).fill('');
  await page.getByRole('button',{name:/^Todos/}).click();
  await choose(filterPanel, 'Ordenar por', 'Nome');
  await expect(list.getByRole('link')).toHaveText([
    /App Raiz revisado/, /Loja Horizonte/, /Plataforma Maré/, /Portal Aurora/, /Site Sol/,
  ]);
  await list.screenshot({path:testInfo.outputPath('prospectos-lista.png')});
  await page.getByRole('button',{name:'Quadro',exact:true}).click();
  await expect(page.locator('.prospect-lane')).toHaveCount(5);
  await page.getByRole('region',{name:'Proposta',exact:true}).getByRole('link',{name:/App Raiz revisado/}).click();
  await expect(page.getByRole('heading',{name:'Empresa exemplo 3',level:1})).toBeVisible();
  await breadcrumb.getByRole('link',{name:'Todos os leads',exact:true}).click();
  await expect(page.locator('.prospect-lane')).toHaveCount(5);
  await page.screenshot({path:testInfo.outputPath('prospectos-quadro.png')});
  await breadcrumb.getByRole('link',{name:'Leads',exact:true}).click();
  await expect(funnel).toBeVisible();
});

test('define ICP e filtra leads pela localização informada, aderência e DDD',async({page})=>{
  await page.setViewportSize({width:390,height:850});
  await page.goto('/#/leads/prospectos');
  const filters=page.getByRole('group',{name:'Filtros de leads'});
  await expect(filters.getByRole('button',{name:'Contatos com DDD 81'})).toHaveCount(0);
  await filters.getByRole('button',{name:'Definir ICP'}).click();
  const dialog=page.getByRole('dialog',{name:'Definir ICP'});
  const min=dialog.getByLabel('Orçamento mínimo (R$)');
  const max=dialog.getByLabel('Orçamento máximo (R$)');
  await min.fill('2000');
  await max.fill('1000');
  await dialog.getByRole('button',{name:'Salvar ICP'}).click();
  await expect(dialog.getByRole('alert')).toContainText('maior ou igual ao mínimo');
  await max.fill('5000');
  await dialog.getByRole('button',{name:'Salvar ICP'}).click();
  await expect(dialog).toBeHidden();
  await filters.getByRole('link',{name:'Novo lead →'}).click();
  const form=page.getByRole('region',{name:'Novo lead'});
  await form.getByText('Ver orçamento do ICP',{exact:true}).click();
  await expect(form.getByText(/Orçamento mínimo/)).toContainText('2.000,00');
  await expect(form.getByText(/Orçamento máximo/)).toContainText('5.000,00');
  await form.getByLabel('Nome da empresa').fill('Empresa do Agreste');
  await form.getByLabel('Contato').fill('+55 (81) 98765-4321');
  await form.getByLabel('Cidade',{exact:true}).fill('Caruaru');
  await form.getByRole('combobox',{name:'UF',exact:true}).selectOption('PE');
  await form.getByLabel('Valor estimado (R$)').fill('3200.50');
  await form.getByRole('combobox',{name:'Aderência ao ICP',exact:true}).selectOption('Fora do ICP');
  await form.getByRole('button',{name:'Salvar lead'}).click();
  await expect(page.getByRole('heading',{name:'Empresa do Agreste',exact:true})).toBeVisible();
  const facts=page.getByRole('region',{name:'Dados do lead'});
  await expect(facts).toContainText('Caruaru / PE');
  await expect(facts).toContainText('3.200,50');
  await expect(facts).toContainText('Fora do ICP');
  await expect(facts).toContainText('Novo');
  await page.goto('/#/leads/prospectos?ddd=81');
  await expect(page.getByText('Contatos com DDD 81',{exact:false})).toBeVisible();
  const table=page.getByRole('table',{name:'Lista de oportunidades'});
  await expect(table.locator('tbody tr')).toHaveCount(1);
  await expect(table).toContainText('Empresa do Agreste');
  for (const [label,option] of [['Cidade','Caruaru'],['UF','PE'],['Aderência ao ICP','Fora do ICP']]) {
    await filters.getByRole('button',{name:label,exact:true}).click();
    await filters.getByRole('group',{name:label,exact:true}).getByRole('button',{name:option}).click();
  }
  await page.reload();
  await expect(table.locator('tbody tr')).toHaveCount(1);
  await filters.getByRole('button',{name:'Definir ICP'}).click();
  await expect(min).toHaveValue('2000');
  await expect(max).toHaveValue('5000');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});