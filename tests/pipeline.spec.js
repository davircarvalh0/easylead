import {test,expect} from './session-fixture.js';
import {seed} from '../src/domain.js';
import {addDemo} from '../src/services/leadProjectService.js';
import {leadActivityDay} from '../src/services/leadActivityService.js';

for(const width of [1280,360]) test(`filtros, médias e fase no percurso ${width}`,async({page},testInfo)=>{
 await page.setViewportSize({width,height:900});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const demo=addDemo(structuredClone(seed));
 const previousYear=Number(leadActivityDay().slice(0,4))-1;
 demo.projects.find(project=>project.name==='Plataforma Maré').contractClosedAt=previousYear+'-12-20';
 await page.addInitScript(state => {
  if (!localStorage.getItem('central-citi-v1')) localStorage.setItem('central-citi-v1', JSON.stringify(state));
 }, demo);
 await page.goto('/#/projetos');
 await expect(page.locator('.bento-revenue .analytics-number')).toHaveText(/^R\$\s*108\.000,00$/);
 await page.getByRole('link',{name:'Todos os projetos →'}).click();
 const portfolio=page.getByRole('region',{name:'Carteira de projetos'});
 await expect(portfolio.locator('.card')).toHaveCount(5);
 await page.getByRole('combobox',{name:'Segmento da contratante',exact:true}).selectOption('Finanças & Pagamentos');
 await page.getByLabel('Fase / Tipo').selectOption('Discovery');
 await page.getByRole('combobox',{name:'Área',exact:true}).selectOption('a0');
 await expect(portfolio.locator('.card')).toHaveCount(1);
 await expect(portfolio).toContainText('72.000,00');
 await page.reload();
 await expect(portfolio.locator('.card')).toHaveCount(1);
 await page.screenshot({path:testInfo.outputPath('projetos-filtrados.png'),fullPage:true,animations:'disabled'});
 await page.getByRole('region',{name:'Carteira de projetos'}).getByRole('link',{name:/Motor IA de Crédito/}).click();
 await expect(page.getByRole('region',{name:'Contrato',exact:true})).toHaveCount(0);
 const projectUrl=page.url();
 await page.getByRole('region',{name:'Dados do projeto'}).getByRole('link',{name:/Motor IA de Crédito/}).click();
 await page.getByRole('link',{name:'Definir valor e escopo'}).click();
 await expect(page.getByLabel('Fase do projeto')).toHaveValue('Discovery');
 await page.getByLabel('Fase do projeto').selectOption('Delivery');
 await page.getByRole('button',{name:'Salvar valor e escopo'}).click();
 await page.getByRole('link',{name:'Ver projeto',exact:true}).click();
 await expect(page).toHaveURL(projectUrl);
 await expect(page.getByRole('region',{name:'Dados do projeto'})).toContainText('Delivery');
 await page.screenshot({path:testInfo.outputPath('dados-do-projeto.png'),fullPage:true,animations:'disabled'});
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('central-citi-v1')));
 expect(saved.projects).toHaveLength(5);
 expect(saved.projects.find(p=>p.name==='Motor IA de Crédito').phase).toBe('Delivery');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 expect(errors).toEqual([]);
});
