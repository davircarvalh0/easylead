import {test,expect} from './session-fixture.js';
for(const width of [360,1280]) test(`exploração ${width}`,async({page})=>{
 await page.setViewportSize({width,height:900});await page.goto('/#/organizacao');
 const scene=page.locator('.citi-orb');await expect(scene).toHaveClass(/is-live/);
 const canvas=await scene.locator('canvas').elementHandle();
 await page.waitForTimeout(900);
 const node=scene.locator('.atom-node').first();await node.focus();await page.keyboard.press('Enter');
 await expect(page.locator('.subarea-atom-detail')).toBeVisible();
 expect(await canvas.evaluate(el=>el.isConnected)).toBe(true);
 await page.waitForTimeout(900);await page.screenshot({path:`evidencias/organizacao/foco-${width}.png`,fullPage:true});
 await page.keyboard.press('Escape');await expect(page).toHaveURL(/#\/organizacao$/);
 await page.waitForTimeout(900);
 const b=await scene.boundingBox();await page.mouse.move(b.x+b.width/2,b.y+150);await page.mouse.down();await page.mouse.move(b.x+b.width/2+80,b.y+180,{steps:10});await page.mouse.up();
 await expect(page).toHaveURL(/#\/organizacao$/);
 await page.getByRole('button',{name:'Aproximar',exact:true}).click();await expect(scene).toHaveAttribute('data-zoom','1.20');
 await page.mouse.move(b.x+b.width/2,b.y+150);await page.mouse.wheel(0,150);await expect(scene).not.toHaveAttribute('data-zoom','1.20');
 await page.emulateMedia({reducedMotion:'reduce'});await expect(scene).toHaveClass(/is-live/);
 await node.focus();await page.keyboard.press('Enter');await expect(page.locator('.subarea-atom-detail')).toBeVisible();
 await page.goto('/#/leads');await page.goto('/#/organizacao');await expect(scene).toHaveClass(/is-live/);
});
test('pinça não seleciona e fallback mantém navegação',async({page})=>{
 await page.goto('/#/organizacao');const scene=page.locator('.citi-orb');await expect(scene).toHaveClass(/is-live/);
 await scene.dispatchEvent('pointerdown',{pointerId:1,pointerType:'touch',clientX:100,clientY:200});
 await scene.dispatchEvent('pointerdown',{pointerId:2,pointerType:'touch',clientX:200,clientY:200});
 await scene.dispatchEvent('pointermove',{pointerId:2,pointerType:'touch',clientX:220,clientY:200});
 await scene.dispatchEvent('pointermove',{pointerId:2,pointerType:'touch',clientX:250,clientY:200});
 await scene.dispatchEvent('pointerup',{pointerId:1});await scene.dispatchEvent('pointerup',{pointerId:2});
 await expect(scene).toHaveAttribute('data-zoom','1.25');await expect(page).toHaveURL(/#\/organizacao$/);
 await page.goto('/?noWebGL#/organizacao');await expect(scene).toHaveClass(/is-static/);
 await scene.locator('.atom-node').first().click();await expect(page.locator('.subarea-atom-detail')).toBeVisible();
});
