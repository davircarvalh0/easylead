import {test,expect} from './session-fixture.js';
import {seed} from '../src/domain.js';
import {conversionDemo} from '../src/services/leadConversionDemo.js';

for(const width of [1280,390]) for(const theme of ['dark','light']) test(`diretórios paginados ${theme} ${width}`,async({page},testInfo)=>{
  await page.setViewportSize({width,height:900});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.addInitScript(({state,theme})=>{
    localStorage.setItem('central-citi-v1',JSON.stringify(state));
    localStorage.setItem('easylead-theme',theme);
  },{state:{...seed,...conversionDemo},theme});
  await page.goto('/#/leads/prospectos');
  await expect(page.getByRole('region',{name:'Pesquisa e filtros de leads'})).toBeVisible();
  await expect(page.getByRole('region',{name:'Todos os leads',exact:true}).getByRole('searchbox')).toHaveCount(0);
  const leads=page.getByRole('table',{name:'Lista de oportunidades'});
  await expect(leads.locator('tbody tr')).toHaveCount(25);
  const leadViewport=page.getByRole('region',{name:'Tabela de prospectos'});
  const leadBounds=await leadViewport.boundingBox();
  const leadRowHeight=(await leads.locator('tbody tr').first().boundingBox()).height;
  const leadPager=page.getByRole('navigation',{name:'Paginação dos leads'});
  await expect(leadPager).toContainText('9.200');
  const first=await leads.locator('tbody tr').first().innerText();
  await leadPager.getByRole('button',{name:'Próxima página'}).click();
  expect(await leads.locator('tbody tr').first().innerText()).not.toBe(first);
  await expect(leads.locator('tbody tr')).toHaveCount(25);
  const secondPage=await leads.locator('tbody tr').first().innerText();
  await leads.locator('.prospect-deal-name').first().click();
  await page.getByRole('navigation',{name:'Caminho da página'}).getByRole('link',{name:'Todos os leads',exact:true}).click();
  await expect.poll(()=>leads.locator('tbody tr').first().innerText()).toBe(secondPage);
  await page.getByRole('searchbox',{name:'Buscar prospectos'}).fill(conversionDemo.leads.at(-1).company);
  await expect(leads.locator('tbody tr')).toHaveCount(1);
  await expect(leadPager).toContainText('1–1 de 1');
  await page.getByRole('searchbox',{name:'Buscar prospectos'}).clear();
  await expect(leads.locator('tbody tr')).toHaveCount(25);
  await expect(leadPager.getByRole('button',{name:'Página anterior'})).toBeDisabled();
  await expect(page.locator('.prospect-module')).toHaveCSS('backdrop-filter','none');
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:testInfo.outputPath('leads.png'),fullPage:true});
  await page.goto('/#/leads/prospectos?modo=quadro');
  const lane=page.getByRole('region',{name:'Novo',exact:true});
  await expect(lane.locator('.prospect-board-item')).toHaveCount(10);
  const laneFirst=await lane.locator('.prospect-card').first().innerText();
  await lane.getByRole('button',{name:'Próxima página'}).click();
  expect(await lane.locator('.prospect-card').first().innerText()).not.toBe(laneFirst);
  expect(await page.locator('.prospect-board-item').count()).toBeLessThanOrEqual(50);
  await page.goto('/#/projetos/todos');
  const projects=page.getByRole('table',{name:'Projetos e contratos'});
  await expect(projects.locator('tbody tr')).toHaveCount(25);
  const projectViewport=page.getByRole('region',{name:'Dados dos contratos'});
  const projectBounds=await projectViewport.boundingBox();
  expect(projectBounds.width).toBeCloseTo(leadBounds.width,1);
  expect(projectBounds.height).toBeCloseTo(leadBounds.height,1);
  expect((await projects.locator('tbody tr').first().boundingBox()).height).toBeCloseTo(leadRowHeight,1);
  const projectPager=page.getByRole('navigation',{name:'Paginação dos contratos'});
  const projectFirst=await projects.locator('tbody tr').first().innerText();
  await projectPager.getByRole('button',{name:'Próxima página'}).click();
  expect(await projects.locator('tbody tr').first().innerText()).not.toBe(projectFirst);
  await page.getByRole('searchbox',{name:'Buscar projetos'}).fill(conversionDemo.projects.at(-1).name);
  await expect(projects.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('searchbox',{name:'Buscar projetos'}).clear();
  await expect(projects.locator('tbody tr')).toHaveCount(25);
  await expect(projectPager.getByRole('button',{name:'Página anterior'})).toBeDisabled();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:testInfo.outputPath('projetos.png'),fullPage:true});
  await page.getByRole('button',{name:'Cartões',exact:true}).click();
  await expect(page.locator('.project-rows .card')).toHaveCount(25);
  await page.getByRole('navigation',{name:'Paginação dos projetos'}).getByRole('button',{name:'Próxima página'}).click();
  await expect(page.locator('.project-rows .card')).toHaveCount(25);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
});
