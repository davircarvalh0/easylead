import {test,expect} from './session-fixture.js';
import {seed} from '../src/domain.js';
import {conversionDemo} from '../src/services/leadConversionDemo.js';

for (const width of [1280,390]) for (const theme of ['light','dark']) test(`dashboards clean ${theme} ${width}px`,async ({page},testInfo)=>{
  await page.setViewportSize({width,height:950});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.addInitScript(({state,theme})=>{
    localStorage.setItem('central-citi-v1',JSON.stringify(state));
    localStorage.setItem('easylead-theme',theme);
  },{state:{...seed,...conversionDemo},theme});
  await page.goto('/#/leads');
  await expect(page.getByRole('heading',{level:1,name:'Leads',exact:true})).toHaveClass(/lead-route-heading/);
  const funnel=page.getByRole('region',{name:'Funil de leads'});
  await expect(funnel).toHaveCSS('backdrop-filter','none');
  await expect(page.getByRole('link',{name:'Novo lead →',exact:true})).toBeVisible();
  await expect(page.getByRole('region',{name:'Conversão em contrato'})).toContainText('4%');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
  const metrics=page.locator('.lead-priority-metrics');
  expect((await metrics.boundingBox()).y).toBeLessThan((await funnel.boundingBox()).y);
  await expect(page.getByText('Visão geral',{exact:true})).toHaveCount(0);
  await expect(page.locator('.easylead-navbar .nimbus-water')).not.toHaveCSS('opacity','0');
  await page.screenshot({path:testInfo.outputPath('leads.png'),fullPage:true});
  await funnel.getByRole('link',{name:/Novo/}).click();
  await expect(page).toHaveURL(/estagio=Novo/);
  await page.goto('/#/projetos');
  await expect(page.getByRole('heading',{level:1,name:'Projetos',exact:true})).toHaveClass(/lead-route-heading/);
  await expect(page.locator('.bento-activity')).toHaveCSS('backdrop-filter','none');
  await expect(page.locator('.dashboard-priority-metrics .priority-metric')).toHaveCount(4);
  expect((await page.locator('.dashboard-priority-metrics').boundingBox()).y).toBeLessThan((await page.locator('.bento-activity').boundingBox()).y);
  const sparkline=page.locator('.sparkline-frame');
  await sparkline.press('End');
  await expect(sparkline.locator('.chart-readout')).toBeVisible();
  await sparkline.press('Escape');
  await expect(sparkline.locator('.chart-readout')).toBeHidden();
  await page.getByRole('button',{name:'Fase',exact:true}).click();
  await expect(page).toHaveURL(/distribuicao=phase/);
  await expect(page.locator('.contract-distribution-bars li')).toHaveCount(1);
  await page.getByRole('button',{name:'Segmento',exact:true}).click();
  await expect(page.locator('.contract-distribution-bars li')).toHaveCount(7);
  await expect(page.locator('.contract-distribution-bars')).toContainText('Outros');
  await expect(page.locator('.bento-categories .bento-legend,.bento-categories .bento-summary')).toHaveCount(0);
  const radar=page.locator('.bento-seasonality .radar-frame');
  expect((await radar.boundingBox()).width).toBeGreaterThan(width>790?400:250);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:testInfo.outputPath('projetos.png'),fullPage:true});
  await page.getByRole('link',{name:'Ver todos os contratos →'}).click();
  await expect(page).toHaveURL(/#\/projetos\/todos\?.*modo=tabela/);
  const table=page.getByRole('table',{name:'Projetos e contratos'});
  await expect(table).toBeVisible();
  await expect(table.locator('tbody tr')).toHaveCount(25);
  const first=await table.locator('tbody tr').first().innerText();
  await page.getByRole('button',{name:'Próxima página'}).click();
  expect(await table.locator('tbody tr').first().innerText()).not.toBe(first);
  await page.getByRole('button',{name:'Página anterior'}).click();
  await expect.poll(()=>table.locator('tbody tr').first().innerText()).toBe(first);
  await page.goto('/#/organizacao/a0');
  await expect(page.locator('.area-dashboard')).toBeVisible();
  await expect(page.locator('.area-stat').first()).toHaveCSS('backdrop-filter','none');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
});
